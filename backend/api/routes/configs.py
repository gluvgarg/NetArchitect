"""Network Device Configuration routes.

Generates syntax-checked router/switch configurations (e.g. Cisco IOS CLI),
provides audit metadata, and enables secure configuration file downloads.
"""

from fastapi import APIRouter, HTTPException, status
from fastapi.responses import FileResponse

from engines.config_generator import ConfigGenerator
from models.config import (
    ConfigGenerationRequest,
    ConfigGenerationResponse,
)

router = APIRouter()
config_generator = ConfigGenerator()


@router.get("/", summary="Configuration Generator Information & History")
def configs_info():
    """Returns configuration generator status, supported targets, and history."""
    return {
        "status": "ready",
        "supported_targets": ["Cisco IOS", "Cisco IOS-XE"],
        "supported_device_types": ["router", "switch"],
        "generated_count": len(config_generator.list_configs()),
        "recent_configs": config_generator.list_configs(),
        "message": "Configuration generator engine is operational.",
    }


@router.post(
    "/generate",
    response_model=ConfigGenerationResponse,
    status_code=status.HTTP_200_OK,
    summary="Generate Device CLI Configuration",
    responses={
        200: {
            "description": "Successfully generated syntax-checked Cisco IOS configuration",
            "model": ConfigGenerationResponse,
        },
        422: {
            "description": "Validation error (duplicate interfaces, invalid IP, contradictory topology, or credentials detected)",
        },
    },
)
def generate_config(request: ConfigGenerationRequest):
    """Generates a complete, validated Cisco IOS configuration script for a router or switch.

    Features:
    - Validates interface IP addressing, subnet masks, and modes (access/trunk/routed).
    - Configures IEEE 802.1Q VLANs and trunk allowed-lists without inventing undeclared VLANs.
    - Configures Single-Area OSPF (Area 0), Multi-Area OSPF, or eBGP peering.
    - Enforces zero plaintext passwords or credential exposure.
    - Persists safe .cfg and .txt artifacts to backend/exports/.
    - Logs traceable audit records to ExplainabilityEngine.
    """
    try:
        result = config_generator.generate_config(request)
        return result
    except ValueError as err:
        http_status = getattr(status, "HTTP_422_UNPROCESSABLE_CONTENT", 422)
        raise HTTPException(
            status_code=http_status,
            detail={
                "error_type": "ValidationError",
                "message": str(err),
            },
        )


@router.get(
    "/{config_id}",
    response_model=ConfigGenerationResponse,
    status_code=status.HTTP_200_OK,
    summary="Retrieve Generated Configuration Details",
    responses={
        200: {"description": "Configuration metadata and complete script"},
        404: {"description": "Configuration ID not found"},
    },
)
def get_config_by_id(config_id: str):
    """Fetches full generated configuration metadata and CLI text for a given config ID."""
    config_data = config_generator.get_config(config_id)
    if not config_data:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Configuration with ID '{config_id}' was not found.",
        )
    return config_data


@router.get(
    "/{config_id}/download",
    summary="Download Generated Configuration File (.cfg)",
    responses={
        200: {
            "description": "Raw Cisco IOS configuration text file (.cfg)",
            "content": {"text/plain": {}},
        },
        404: {"description": "Exported configuration file not found"},
    },
)
def download_config_file(config_id: str):
    """Securely downloads the generated .cfg file.

    Restricted strictly to files generated by this engine within backend/exports/.
    """
    file_path = config_generator.get_export_file_path(config_id)
    if not file_path or not file_path.is_file():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Configuration file for ID '{config_id}' was not found or has been removed.",
        )

    return FileResponse(
        path=file_path,
        media_type="text/plain",
        filename=file_path.name,
    )
